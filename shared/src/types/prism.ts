/**
 * Canonical Data Contract for Prism 3D CAD Analysis & Reports
 * Standard: dfn-docs/02-data-contracts-schemas.md & dfn-prism/src/prism/report/builder.py
 */

export interface SourceFileManifest {
  filename: string;
  format: 'STEP' | 'IGES' | 'STL' | string;
  size_bytes: number;
  hash_sha256: string;
}

export interface BoundingBox3D {
  x_mm: number;
  y_mm: number;
  z_mm: number;
}

export interface GeometryManifest {
  volume_mm3?: number;
  surface_area_mm2?: number;
  bounding_box: BoundingBox3D;
  center_of_mass_mm?: [number, number, number];
  aspect_ratio?: number;
  surface_to_volume_ratio?: number;
  is_watertight: boolean;
  face_count?: number;
  edge_count?: number;
  shell_count?: number;
  face_type_distribution?: Record<string, number>;
}

export interface FeatureManifest {
  type:
    | 'through_hole'
    | 'blind_hole'
    | 'pocket'
    | 'fillet'
    | 'chamfer'
    | 'boss'
    | 'slot'
    | 'thread'
    | string;
  diameter_mm?: number;
  depth_mm?: number;
  location_mm?: number[];
  axis?: number[];
  confidence: number;
}

export interface MaterialInference {
  inferred: 'aluminum_alloy' | 'mild_steel' | 'stainless_steel' | 'plastic' | 'unknown' | string;
  confidence?: number;
  source: 'step_metadata' | 'inferred' | 'user_provided' | string;
  density_kg_m3?: number;
}

export interface WorkflowStep {
  process: string;
  confidence: number;
  is_primary: boolean;
}

export interface WorkflowProposal {
  steps: WorkflowStep[];
  reasoning?: string;
  estimated_complexity?: 'Low' | 'Medium' | 'High' | string;
}

export interface DfmIssue {
  type: string;
  severity: 'info' | 'warning' | 'critical' | string;
  value?: number;
  threshold?: number;
  unit?: string;
  location_mm?: number[];
  message: string;
}

export interface PrismBopOperation {
  op_number: number;
  process_id: string;
  description: string;
  machine_type?: string;
  setup_description?: string;
  tooling?: Array<{ tool_id: string }>;
  estimated_cycle_time_min?: { min: number; max: number };
}

export interface PrismBopManifest {
  bop_id?: string;
  operations: PrismBopOperation[];
}

export interface PrismBomItem {
  line_number: number;
  part_number: string;
  description: string;
  material?: string;
  quantity: number;
  unit?: string;
}

export interface PrismBomManifest {
  bom_id?: string;
  items: PrismBomItem[];
}

export interface PrismMetadata {
  parser_version?: string;
  inference_engine?: string;
  llm_model?: string;
  processing_time_ms?: number;
}

/**
 * Versioned Canonical Manifest generated by dfn-prism
 */
export interface PrismReportManifest {
  schema_version: '1.1' | string;
  report_id: string;
  job_id: string;
  created_at: string;
  source_file: SourceFileManifest;
  geometry: GeometryManifest;
  features: FeatureManifest[];
  material: MaterialInference;
  is_assembly?: boolean;
  part_count?: number;
  parts?: any[];
  workflows: WorkflowProposal[];
  dfm_issues: DfmIssue[];
  complexity_score: number; // 0.0 - 10.0
  metadata?: PrismMetadata;
  bop?: PrismBopManifest | null;
  bom?: PrismBomManifest | null;
}
